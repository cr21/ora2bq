CREATE TABLE "RETAIL"."CUSTOMERS" 
   (	"CUSTOMER_ID" NUMBER(10,0) GENERATED BY DEFAULT AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 2001 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, 
	"FIRST_NAME" VARCHAR2(50) NOT NULL ENABLE, 
	"LAST_NAME" VARCHAR2(50) NOT NULL ENABLE, 
	"EMAIL" VARCHAR2(120) NOT NULL ENABLE, 
	"PHONE" VARCHAR2(20), 
	"CITY" VARCHAR2(60), 
	"STATE_CODE" CHAR(2), 
	"REGION" VARCHAR2(12) NOT NULL ENABLE, 
	"SIGNUP_DATE" DATE NOT NULL ENABLE, 
	"LOYALTY_TIER" VARCHAR2(10) DEFAULT 'BRONZE' NOT NULL ENABLE, 
	"IS_ACTIVE" CHAR(1) DEFAULT 'Y' NOT NULL ENABLE, 
	"CREATED_AT" TIMESTAMP (6) DEFAULT SYSTIMESTAMP NOT NULL ENABLE, 
	"UPDATED_AT" TIMESTAMP (6), 
	 CONSTRAINT "CK_CUSTOMERS_REGION" CHECK (region IN ('NORTHEAST','SOUTHEAST','MIDWEST','SOUTHWEST','WEST')) ENABLE, 
	 CONSTRAINT "CK_CUSTOMERS_TIER" CHECK (loyalty_tier IN ('BRONZE','SILVER','GOLD','PLATINUM')) ENABLE, 
	 CONSTRAINT "CK_CUSTOMERS_ACTIVE" CHECK (is_active IN ('Y','N')) ENABLE, 
	 CONSTRAINT "PK_CUSTOMERS" PRIMARY KEY ("CUSTOMER_ID")
  USING INDEX  ENABLE, 
	 CONSTRAINT "UQ_CUSTOMERS_EMAIL" UNIQUE ("EMAIL")
  USING INDEX  ENABLE
   ) ;

CREATE UNIQUE INDEX "RETAIL"."UQ_CUSTOMERS_EMAIL" ON "RETAIL"."CUSTOMERS" ("EMAIL") 
  ;
  CREATE UNIQUE INDEX "RETAIL"."PK_CUSTOMERS" ON "RETAIL"."CUSTOMERS" ("CUSTOMER_ID") 
  ;
