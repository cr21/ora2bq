CREATE TABLE "RETAIL"."PRODUCTS" 
   (	"PRODUCT_ID" NUMBER(8,0) GENERATED BY DEFAULT AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 501 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, 
	"SKU" VARCHAR2(20) NOT NULL ENABLE, 
	"PRODUCT_NAME" VARCHAR2(150) NOT NULL ENABLE, 
	"CATEGORY_ID" NUMBER(6,0) NOT NULL ENABLE, 
	"SUPPLIER_ID" NUMBER(6,0) NOT NULL ENABLE, 
	"UNIT_COST" NUMBER(10,2) NOT NULL ENABLE, 
	"LIST_PRICE" NUMBER(10,2) NOT NULL ENABLE, 
	"WEIGHT_KG" NUMBER(7,3), 
	"LAUNCH_DATE" DATE NOT NULL ENABLE, 
	"IS_DISCONTINUED" CHAR(1) DEFAULT 'N' NOT NULL ENABLE, 
	 CONSTRAINT "CK_PRODUCTS_PRICE" CHECK (unit_cost > 0 AND list_price >= unit_cost) ENABLE, 
	 CONSTRAINT "CK_PRODUCTS_DISC" CHECK (is_discontinued IN ('Y','N')) ENABLE, 
	 CONSTRAINT "PK_PRODUCTS" PRIMARY KEY ("PRODUCT_ID")
  USING INDEX  ENABLE, 
	 CONSTRAINT "UQ_PRODUCTS_SKU" UNIQUE ("SKU")
  USING INDEX  ENABLE, 
	 CONSTRAINT "FK_PRODUCTS_CATEGORY" FOREIGN KEY ("CATEGORY_ID")
	  REFERENCES "RETAIL"."PRODUCT_CATEGORIES" ("CATEGORY_ID") ENABLE, 
	 CONSTRAINT "FK_PRODUCTS_SUPPLIER" FOREIGN KEY ("SUPPLIER_ID")
	  REFERENCES "RETAIL"."SUPPLIERS" ("SUPPLIER_ID") ENABLE
   ) ;

CREATE UNIQUE INDEX "RETAIL"."PK_PRODUCTS" ON "RETAIL"."PRODUCTS" ("PRODUCT_ID") 
  ;
  CREATE INDEX "RETAIL"."IX_PRODUCTS_CATEGORY" ON "RETAIL"."PRODUCTS" ("CATEGORY_ID") 
  ;
  CREATE INDEX "RETAIL"."IX_PRODUCTS_SUPPLIER" ON "RETAIL"."PRODUCTS" ("SUPPLIER_ID") 
  ;
  CREATE UNIQUE INDEX "RETAIL"."UQ_PRODUCTS_SKU" ON "RETAIL"."PRODUCTS" ("SKU") 
  ;
