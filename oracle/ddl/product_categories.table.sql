CREATE TABLE "RETAIL"."PRODUCT_CATEGORIES" 
   (	"CATEGORY_ID" NUMBER(6,0) NOT NULL ENABLE, 
	"CATEGORY_NAME" VARCHAR2(60) NOT NULL ENABLE, 
	"PARENT_CATEGORY_ID" NUMBER(6,0), 
	"CATEGORY_LEVEL" NUMBER(1,0) NOT NULL ENABLE, 
	"IS_ACTIVE" CHAR(1) DEFAULT 'Y' NOT NULL ENABLE, 
	 CONSTRAINT "CK_CATEGORY_LEVEL" CHECK (category_level IN (1, 2, 3)) ENABLE, 
	 CONSTRAINT "CK_CATEGORY_ACTIVE" CHECK (is_active IN ('Y','N')) ENABLE, 
	 CONSTRAINT "PK_PRODUCT_CATEGORIES" PRIMARY KEY ("CATEGORY_ID")
  USING INDEX  ENABLE, 
	 CONSTRAINT "FK_CATEGORY_PARENT" FOREIGN KEY ("PARENT_CATEGORY_ID")
	  REFERENCES "RETAIL"."PRODUCT_CATEGORIES" ("CATEGORY_ID") ENABLE
   ) ;

CREATE UNIQUE INDEX "RETAIL"."PK_PRODUCT_CATEGORIES" ON "RETAIL"."PRODUCT_CATEGORIES" ("CATEGORY_ID") 
  ;
