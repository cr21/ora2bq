CREATE TABLE "RETAIL"."ORDER_RETURNS" 
   (	"RETURN_ID" NUMBER(12,0) GENERATED BY DEFAULT AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 1 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, 
	"ORDER_ID" NUMBER(12,0) NOT NULL ENABLE, 
	"ORDER_ITEM_ID" NUMBER(14,0) NOT NULL ENABLE, 
	"PRODUCT_ID" NUMBER(8,0) NOT NULL ENABLE, 
	"RETURN_DATE" DATE NOT NULL ENABLE, 
	"QUANTITY" NUMBER(6,0) NOT NULL ENABLE, 
	"RETURN_REASON" VARCHAR2(20) NOT NULL ENABLE, 
	"ITEM_CONDITION" VARCHAR2(10) NOT NULL ENABLE, 
	"RETURN_STATUS" VARCHAR2(10) NOT NULL ENABLE, 
	"REFUND_AMOUNT" NUMBER(12,2), 
	"RESTOCKED_QTY" NUMBER(6,0), 
	"PROCESSED_AT" TIMESTAMP (6), 
	"REJECT_REASON" VARCHAR2(200), 
	 CONSTRAINT "CK_ORDER_RETURNS_QTY" CHECK (quantity > 0) ENABLE, 
	 CONSTRAINT "CK_ORDER_RETURNS_REASON" CHECK (return_reason IN ('DAMAGED','WRONG_ITEM','NOT_AS_DESCRIBED','CHANGED_MIND','LATE_DELIVERY')) ENABLE, 
	 CONSTRAINT "CK_ORDER_RETURNS_COND" CHECK (item_condition IN ('NEW','OPENED','DAMAGED')) ENABLE, 
	 CONSTRAINT "CK_ORDER_RETURNS_STATUS" CHECK (return_status IN ('REQUESTED','RECEIVED','PROCESSED','REJECTED')) ENABLE, 
	 CONSTRAINT "PK_ORDER_RETURNS" PRIMARY KEY ("RETURN_ID")
  USING INDEX  ENABLE, 
	 CONSTRAINT "FK_ORDER_RETURNS_ORDER" FOREIGN KEY ("ORDER_ID")
	  REFERENCES "RETAIL"."ORDERS" ("ORDER_ID") ENABLE, 
	 CONSTRAINT "FK_ORDER_RETURNS_ITEM" FOREIGN KEY ("ORDER_ITEM_ID")
	  REFERENCES "RETAIL"."ORDER_ITEMS" ("ORDER_ITEM_ID") ENABLE, 
	 CONSTRAINT "FK_ORDER_RETURNS_PRODUCT" FOREIGN KEY ("PRODUCT_ID")
	  REFERENCES "RETAIL"."PRODUCTS" ("PRODUCT_ID") ENABLE
   ) ;

CREATE UNIQUE INDEX "RETAIL"."PK_ORDER_RETURNS" ON "RETAIL"."ORDER_RETURNS" ("RETURN_ID") 
  ;
  CREATE INDEX "RETAIL"."IX_ORDER_RETURNS_ORDER" ON "RETAIL"."ORDER_RETURNS" ("ORDER_ID") 
  ;
  CREATE INDEX "RETAIL"."IX_ORDER_RETURNS_STATUS" ON "RETAIL"."ORDER_RETURNS" ("RETURN_STATUS", "RETURN_DATE") 
  ;
