CREATE TABLE "RETAIL"."ORDERS" 
   (	"ORDER_ID" NUMBER(12,0) GENERATED BY DEFAULT AS IDENTITY MINVALUE 1 MAXVALUE 9999999999999999999999999999 INCREMENT BY 1 START WITH 120001 CACHE 20 NOORDER  NOCYCLE  NOKEEP  NOSCALE  NOT NULL ENABLE, 
	"CUSTOMER_ID" NUMBER(10,0) NOT NULL ENABLE, 
	"ORDER_DATE" DATE NOT NULL ENABLE, 
	"ORDER_STATUS" VARCHAR2(12) NOT NULL ENABLE, 
	"CHANNEL" VARCHAR2(8) NOT NULL ENABLE, 
	"SHIP_WAREHOUSE_ID" NUMBER(4,0), 
	"DISCOUNT_AMOUNT" NUMBER(12,2) DEFAULT 0 NOT NULL ENABLE, 
	"TAX_AMOUNT" NUMBER(12,2) DEFAULT 0 NOT NULL ENABLE, 
	"SHIPPING_FEE" NUMBER(8,2) DEFAULT 0 NOT NULL ENABLE, 
	"ORDER_TOTAL" NUMBER(12,2) NOT NULL ENABLE, 
	"CURRENCY_CODE" CHAR(3) DEFAULT 'USD' NOT NULL ENABLE, 
	"DQ_STATUS" VARCHAR2(10) DEFAULT 'UNCHECKED' NOT NULL ENABLE, 
	"DQ_MESSAGE" VARCHAR2(400), 
	"DQ_CHECKED_AT" TIMESTAMP (6), 
	"CREATED_AT" TIMESTAMP (6) DEFAULT SYSTIMESTAMP NOT NULL ENABLE, 
	"UPDATED_AT" TIMESTAMP (6), 
	 CONSTRAINT "CK_ORDERS_STATUS" CHECK (order_status IN ('PENDING','PAID','SHIPPED','DELIVERED','CANCELLED','RETURNED','ON_HOLD')) ENABLE, 
	 CONSTRAINT "CK_ORDERS_CHANNEL" CHECK (channel IN ('WEB','MOBILE','STORE','PHONE')) ENABLE, 
	 CONSTRAINT "CK_ORDERS_DQ" CHECK (dq_status IN ('UNCHECKED','PASSED','FIXED','WARNING','FAILED')) ENABLE, 
	 CONSTRAINT "PK_ORDERS" PRIMARY KEY ("ORDER_ID")
  USING INDEX  ENABLE, 
	 CONSTRAINT "FK_ORDERS_CUSTOMER" FOREIGN KEY ("CUSTOMER_ID")
	  REFERENCES "RETAIL"."CUSTOMERS" ("CUSTOMER_ID") ENABLE, 
	 CONSTRAINT "FK_ORDERS_WAREHOUSE" FOREIGN KEY ("SHIP_WAREHOUSE_ID")
	  REFERENCES "RETAIL"."WAREHOUSES" ("WAREHOUSE_ID") ENABLE
   ) ;

CREATE INDEX "RETAIL"."IX_ORDERS_DATE" ON "RETAIL"."ORDERS" ("ORDER_DATE") 
  ;
  CREATE UNIQUE INDEX "RETAIL"."PK_ORDERS" ON "RETAIL"."ORDERS" ("ORDER_ID") 
  ;
  CREATE INDEX "RETAIL"."IX_ORDERS_WAREHOUSE" ON "RETAIL"."ORDERS" ("SHIP_WAREHOUSE_ID") 
  ;
  CREATE INDEX "RETAIL"."IX_ORDERS_STATUS" ON "RETAIL"."ORDERS" ("ORDER_STATUS", "DQ_STATUS") 
  ;
  CREATE INDEX "RETAIL"."IX_ORDERS_CUSTOMER" ON "RETAIL"."ORDERS" ("CUSTOMER_ID") 
  ;
